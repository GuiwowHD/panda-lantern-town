export function getUnit(unitId: Unit["id"]) {
  return UNITS.find((unit) => unit.id === unitId)!;
}

export function getListenRounds(unit: Unit) {
  return unit.words.map((target, roundIndex) => {
    const alternatives = unit.words.filter((id) => id !== target);
    const options: WordId[] = [
      target,
      alternatives[roundIndex % alternatives.length],
      alternatives[(roundIndex + 2) % alternatives.length],
    ];
    const rotation = roundIndex % options.length;
    return {
      target,
      options: [...options.slice(rotation), ...options.slice(0, rotation)],
    };
  });
}
